/** Oblici za množinu (`Intl.PluralRules`): hr ima one / few / other, en one / other. */
export interface Mnozina {
  one: string;
  few: string;
  other: string;
}

export function mnozina(lang: Lang, n: number, m: Mnozina): string {
  const k = new Intl.PluralRules(LOCALE[lang]).select(n);
  return `${new Intl.NumberFormat(LOCALE[lang]).format(n)} ${k === "one" ? m.one : k === "few" ? m.few : m.other}`;
}

